"""Multi-POU project emitter for CODESYS-family (and strict IEC) targets.

Architecture of the emitted project, per legacy program <PID>:

    GVL_IO      physical I/O (X -> xDI_*, Y -> xDO_*); TwinCAT: AT %I* / %Q*
    GVL_MEM     M relays, D registers, timer/counter instances, first-scan
    GVL_RETAIN  L relays and R file registers (VAR_GLOBAL RETAIN/PERSISTENT)
    PRG_<PID>_Snn  one PROGRAM per segment of at most N networks; edge and
                   pulse trigger instances stay local (per-instruction state)
    PRG_<PID>      calls the segments in source order, then clears the
                   first-scan flag. This is the POU to put in the task.

Segment boundaries fall only between networks and never inside an open MC
zone, so the H4 restructuring an engineer does later stays in one POU.
Several legacy programs can be consolidated into one project: GVLs get the
program prefix (GVL_<PID>_IO ...) and CODESYS-family access is qualified
(GVL.var) with qualified_only, so device names can never collide. Strict IEC
targets get unqualified access plus VAR_EXTERNAL lists instead.

Output is deterministic: same inputs and options -> byte-identical files.
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace
from typing import Optional

from ..ir import Op, Program, Rung
from ..targets import DEFAULT_TARGET, Target, get_target
from .plcopen import GvlSpec, PouSpec, build_project_xml
from .st import (Translator, VarDecl, draft_header, flags_by_step,
                 network_header, safety_banner, sanitize_ident, sorted_decls,
                 var_block)

_ROLE_OF_KIND = {"input": "io", "output": "io", "mem": "mem", "fb": "mem",
                 "retain": "retain"}


@dataclass
class ProjectOptions:
    target: str = DEFAULT_TARGET
    naming: str = "legacy"              # legacy | symbolic
    max_networks_per_pou: int = 0       # 0 = one POU per program
    timer_base_ms: int = 100
    project_name: str = "ptts_migration"
    timestamp: Optional[str] = None     # None = fixed, reproducible stamp
    task_interval_ms: int = 10


@dataclass
class Pou:
    name: str
    kind: str                           # "segment" | "main"
    program: str
    header: str
    statements: str
    locals: list[VarDecl] = field(default_factory=list)
    externals: list[VarDecl] = field(default_factory=list)
    steps: list[int] = field(default_factory=list)
    calls: list[str] = field(default_factory=list)

    @property
    def body(self) -> str:
        return self.header + self.statements


@dataclass
class Gvl:
    name: str
    program: str
    role: str                           # io | mem | retain
    vars: list[VarDecl]
    retain_kw: str = ""                 # "" | RETAIN | PERSISTENT
    qualified_only: bool = True
    io_alloc: str = "none"

    def address_of(self, v: VarDecl) -> Optional[str]:
        if self.role != "io" or self.io_alloc != "twincat_star":
            return None
        return "%I*" if v.kind == "input" else "%Q*"


@dataclass
class ProjectModel:
    options: ProjectOptions
    target: Target
    pous: list[Pou]
    gvls: list[Gvl]
    programs: list[str]
    summaries: dict
    fb_types: list[str]

    @property
    def safety_boundary(self) -> bool:
        return any(s["safety_boundary"] for s in self.summaries.values())

    @property
    def main_pous(self) -> list[str]:
        return [p.name for p in self.pous if p.kind == "main"]

    @property
    def libraries(self) -> dict:
        return {
            "target": self.target.id,
            "ide": self.target.ide,
            "fb_types_used": self.fb_types,
            "libraries": [lib.__dict__ for lib in self.target.libraries],
            "note": ("Add the required libraries in the IDE's Library "
                     "Manager before building. Library versions are not "
                     "pinned here — use the version shipped with your IDE "
                     "release and record it in the project."),
        }

    def st_files(self) -> dict[str, str]:
        files: dict[str, str] = {}
        for g in self.gvls:
            head = (f"(* {g.name} - {g.role} globals of legacy program "
                    f"{g.program}; generated by dummvinci-rosetta-plc "
                    f"for {self.target.id} *)\n")
            if self.target.gvl_style == "tc6_resource":
                head += ("(* strict IEC: these belong to configuration "
                         "Config / resource Resource in the PLCopen file *)\n")
            pragma = "{attribute 'qualified_only'}\n" if g.qualified_only \
                else ""
            kw = "VAR_GLOBAL" + (f" {g.retain_kw}" if g.retain_kw else "")
            files[f"{g.name}.st"] = head + pragma + var_block(
                kw, g.vars, g.address_of)
        for p in self.pous:
            files[f"{p.name}.st"] = (
                p.header + f"PROGRAM {p.name}\n"
                + var_block("VAR", p.locals)
                + var_block("VAR_EXTERNAL", p.externals)
                + "\n" + p.statements + "\nEND_PROGRAM\n")
        return files

    def plcopen_xml(self) -> str:
        pous = [PouSpec(p.name, p.body, [("localVars", p.locals, {}),
                                         ("externalVars", p.externals, {})])
                for p in self.pous]
        gvls = [GvlSpec(g.name, g.vars, retain=g.retain_kw == "RETAIN",
                        persistent=g.retain_kw == "PERSISTENT",
                        qualified_only=g.qualified_only,
                        address_of=g.address_of) for g in self.gvls]
        return build_project_xml(
            self.options.project_name, pous, gvls, self.target,
            timestamp=self.options.timestamp, task_pous=self.main_pous,
            task_interval=f"T#{self.options.task_interval_ms}ms",
            description=f"target={self.target.id}")


def segment_rungs(rungs: list[Rung], max_networks: int) -> list[list[Rung]]:
    """Chunks of at most max_networks networks; a chunk is extended until
    any MC zone opened inside it is closed again."""
    if max_networks <= 0 or len(rungs) <= max_networks:
        return [list(rungs)]
    chunks, cur, depth = [], [], 0
    for r in rungs:
        cur.append(r)
        for i in r.instructions:
            if i.op is Op.MC:
                depth += 1
            elif i.op is Op.MCR:
                depth = max(0, depth - 1)
        if len(cur) >= max_networks and depth == 0:
            chunks.append(cur)
            cur = []
    if cur:
        chunks.append(cur)
    return chunks


def _program_ids(progs: list[Program]) -> list[str]:
    ids = []
    for i, p in enumerate(progs):
        pid = sanitize_ident(p.name, max_len=24) or f"P{i + 1}"
        if pid[0].isdigit():
            pid = f"P{pid}"
        ids.append(pid)
    dupes = sorted({x for x in ids if ids.count(x) > 1})
    if dupes:
        raise ValueError(f"program ids collide after sanitising: {dupes} — "
                         f"give each program a distinct id")
    return ids


def emit_project(items: list[tuple[Program, dict]],
                 options: Optional[ProjectOptions] = None) -> ProjectModel:
    opt = options or ProjectOptions()
    tgt = get_target(opt.target, for_emit=True)
    if not items:
        raise ValueError("no programs to emit")
    progs = [p for p, _ in items]
    pids = _program_ids(progs)
    multi = len(items) > 1
    pous: list[Pou] = []
    gvls: list[Gvl] = []
    summaries: dict = {}
    fb_types: set[str] = set()

    for (prog, flags), pid in zip(items, pids):
        stem = f"GVL_{pid}_" if multi else "GVL_"
        gname = {"io": f"{stem}IO", "mem": f"{stem}MEM",
                 "retain": f"{stem}RETAIN"}

        def qualify(kind: str, _g=gname) -> Optional[str]:
            return _g[_ROLE_OF_KIND[kind]]

        tr = Translator(prog, tgt, naming=opt.naming,
                        timer_base_ms=opt.timer_base_ms,
                        qualify=qualify if tgt.qualified_access else None)
        by_step = flags_by_step(flags)
        banner = safety_banner(flags)
        chunks = segment_rungs(prog.rungs, opt.max_networks_per_pou)
        width = max(2, len(str(len(chunks))))
        single = len(chunks) == 1

        def externals() -> list[VarDecl]:
            if tgt.qualified_access:
                return []
            # IEC: VAR_EXTERNAL carries no initial value (the GVL owns it)
            return [replace(v, init=None) for v in sorted_decls(
                tr.decls[n] for n in tr.used if n in tr.decls)]

        def end_of_scan() -> str:
            return (f"{tr.first_scan_ref()} := FALSE;  (* end of scan: "
                    f"first-scan flag is TRUE only during the first cycle *)")

        seg_pous: list[Pou] = []
        for k, rungs in enumerate(chunks):
            tr.begin_pou()
            name = f"PRG_{pid}" if single else f"PRG_{pid}_S{k + 1:0{width}d}"
            lines: list[str] = []
            for r in rungs:
                lines.extend(network_header(r, by_step))
                lines.extend(tr.translate_rung(r))
                lines.append("")
            if single:
                lines.append(end_of_scan())
            seg_pous.append(Pou(
                name=name, kind="main" if single else "segment", program=pid,
                header=banner + draft_header(name, prog, tgt,
                                             opt.timer_base_ms),
                statements="\n".join(lines), locals=sorted_decls(
                    tr.locals.values()), externals=externals(),
                steps=[r.start_step for r in rungs]))
        pous.extend(seg_pous)
        if not single:
            tr.begin_pou()
            calls = [p.name for p in seg_pous]
            stmts = ("(* segments in legacy scan order *)\n"
                     + "\n".join(f"{c}();" for c in calls) + "\n"
                     + end_of_scan())
            pous.append(Pou(
                name=f"PRG_{pid}", kind="main", program=pid,
                header=banner + draft_header(f"PRG_{pid}", prog, tgt,
                                             opt.timer_base_ms),
                statements=stmts, externals=externals(), calls=calls))

        by_role: dict[str, list[VarDecl]] = {"io": [], "mem": [], "retain": []}
        for v in tr.decls.values():
            by_role[_ROLE_OF_KIND[v.kind]].append(v)
        for role in ("io", "mem", "retain"):
            if not by_role[role]:
                continue
            gvls.append(Gvl(
                name=gname[role], program=pid, role=role,
                vars=sorted_decls(by_role[role]),
                retain_kw=tgt.retain_keyword if role == "retain" else "",
                qualified_only=tgt.qualified_access, io_alloc=tgt.io_alloc))
        fb_types |= tr.fb_types
        s = (flags or {}).get("summary", {})
        summaries[pid] = {
            "source_name": prog.name,
            "BLOCKER": s.get("BLOCKER", 0), "MAJOR": s.get("MAJOR", 0),
            "MINOR": s.get("MINOR", 0),
            "safety_boundary": bool(s.get("safety_boundary")),
            "safety_categories": s.get("safety_categories", []),
            "verdict": s.get("verdict", ""),
            "networks": len(prog.rungs),
            "pous": [p.name for p in pous if p.program == pid],
            "main_pou": f"PRG_{pid}",
        }

    names = [p.name for p in pous] + [g.name for g in gvls]
    clash = sorted({n for n in names if names.count(n) > 1})
    if clash:
        raise ValueError(f"object name collision in project: {clash}")
    return ProjectModel(opt, tgt, pous, gvls, pids, summaries,
                        sorted(fb_types))
