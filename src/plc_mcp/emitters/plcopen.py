def lint_st(st_code: str) -> dict:
    """Cheap structural lint: pairing, unterminated statements, leftover
    TODO/UNTRANSLATED markers. Not a compiler — Automation Builder is the
    final authority."""
    import re
    issues, warnings = [], []
    # Structural counting must ignore comments — TODO markers legitimately
    # contain words like IF without END_IF (audit M-2).
    # A small lexer preserves newlines and handles nested IEC comments,
    # line comments, and strings so their keywords do not affect pairing.
    tokens, index, depth, quote = [], 0, 0, None
    while index < len(st_code):
        pair = st_code[index:index + 2]
        char = st_code[index]
        if depth:
            if pair == "(*":
                depth += 1
                index += 2
                continue
            if pair == "*)":
                depth -= 1
                index += 2
                continue
            tokens.append("\n" if char == "\n" else " ")
        elif quote:
            if char == quote:
                if index + 1 < len(st_code) and st_code[index + 1] == quote:
                    index += 2
                    continue
                quote = None
            tokens.append("\n" if char == "\n" else " ")
        elif pair == "(*":
            depth = 1
            index += 2
            continue
        elif pair == "//":
            end = st_code.find("\n", index)
            if end == -1:
                break
            index = end
            continue
        elif char in ("'", '"'):
            quote = char
            tokens.append(" ")
        else:
            tokens.append(char)
        index += 1
    if depth:
        issues.append("Unterminated IEC comment")
    if quote:
        issues.append("Unterminated string literal")
    code_only = "".join(tokens).upper()
    n_if = len(re.findall(r"\bIF\b", code_only))
    n_endif = len(re.findall(r"\bEND_IF\b", code_only))
    if n_if != n_endif:
        issues.append(f"IF/END_IF mismatch: {n_if} IF vs {n_endif} END_IF")
    n_var = len(re.findall(r"^\s*VAR(?:\s+RETAIN|_INPUT|_OUTPUT)?\s*$",
                           code_only, re.M))
    n_endvar = len(re.findall(r"\bEND_VAR\b", code_only))
    if n_var != n_endvar:
        issues.append(f"VAR/END_VAR mismatch: {n_var} vs {n_endvar}")
    todos = re.findall(r"\(\*\s*TODO(?:\s+\[([^\]]+)\])?", st_code)
    if todos:
        from collections import Counter
        for code, cnt in Counter(todos).most_common():
            warnings.append(f"{cnt}x unresolved TODO [{code or 'unclassified'}]")
    unt = st_code.count("UNTRANSLATED")
    if unt:
        issues.append(f"{unt} UNTRANSLATED instruction(s) remain")
    unmapped = st_code.count("UNMAPPED")
    if unmapped:
        issues.append(f"{unmapped} UNMAPPED device reference(s)")
    return {"ok": not issues, "issues": issues, "warnings": warnings,
            "note": "Structural lint only — final compile check must be "
                    "done in Automation Builder / TIA Portal."}
