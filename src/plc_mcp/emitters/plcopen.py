_ST_KEYWORDS = {"IF", "THEN", "ELSE", "ELSIF", "END_IF", "CASE", "OF",
                "END_CASE", "FOR", "TO", "DO", "END_FOR", "WHILE",
                "END_WHILE", "TRUE", "FALSE", "AND", "OR", "NOT", "XOR",
                "MOD", "PROGRAM", "END_PROGRAM", "VAR", "VAR_INPUT",
                "VAR_OUTPUT", "END_VAR", "RETAIN", "FUNCTION_BLOCK",
                "END_FUNCTION_BLOCK"}


def lint_st(st_code: str) -> dict:
    """Cheap structural lint: pairing, unterminated statements, leftover
    TODO/UNTRANSLATED markers. Not a compiler — Automation Builder is the
    final authority."""
    import re
    issues, warnings = [], []
    n_if = len(re.findall(r"\bIF\b", st_code))
    n_endif = len(re.findall(r"\bEND_IF\b", st_code))
    if n_if != n_endif:
        issues.append(f"IF/END_IF mismatch: {n_if} IF vs {n_endif} END_IF")
    n_var = len(re.findall(r"^\s*VAR(?:\s+RETAIN|_INPUT|_OUTPUT)?\s*$",
                           st_code, re.M))
    n_endvar = len(re.findall(r"\bEND_VAR\b", st_code))
    if n_var != n_endvar:
        issues.append(f"VAR/END_VAR mismatch: {n_var} vs {n_endvar}")
    todos = re.findall(r"\(\* ?TODO \[(H\d+[^\]]*)\]", st_code)
    if todos:
        from collections import Counter
        for code, cnt in Counter(todos).most_common():
            warnings.append(f"{cnt}x unresolved TODO [{code}]")
    unt = st_code.count("UNTRANSLATED")
    if unt:
        issues.append(f"{unt} UNTRANSLATED instruction(s) remain")
    unmapped = st_code.count("UNMAPPED")
    if unmapped:
        issues.append(f"{unmapped} UNMAPPED device reference(s)")
    return {"ok": not issues, "issues": issues, "warnings": warnings,
            "note": "Structural lint only — final compile check must be "
                    "done in Automation Builder / TIA Portal."}
