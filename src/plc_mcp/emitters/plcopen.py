"""PLCopen XML emitter — wraps generated ST into a PLCopen TC6 XML project
importable by ABB Automation Builder / CODESYS (and other IEC tools)."""
from __future__ import annotations

from datetime import datetime, timezone
import re
from xml.sax.saxutils import escape, quoteattr

from ..ir import validate_iec_identifier
from ..analysis.semantics import reject_safety_text


def emit_plcopen_xml(st_code: str, pou_name: str = "PRG_Converted",
                     project_name: str = "ptts_migration") -> str:
    validate_iec_identifier(pou_name, "pou_name")
    reject_safety_text(st_code, pou_name, project_name)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
    # split declaration part and body part
    if "END_VAR" in st_code:
        idx = st_code.rfind("END_VAR") + len("END_VAR")
        decl, body = st_code[:idx], st_code[idx:]
    else:
        decl, body = "", st_code
    # PLCopen carries the interface separately; we keep full decl text in
    # documentation and the body as ST — pragmatic and AB-import friendly.
    return f"""<?xml version="1.0" encoding="utf-8"?>
<project xmlns="http://www.plcopen.org/xml/tc6_0200">
  <fileHeader companyName="PTTS" productName="dummvinci-rosetta-plc"
              productVersion="0.2" creationDateTime="{now}"/>
  <contentHeader name={quoteattr(project_name)} modificationDateTime="{now}">
    <coordinateInfo>
      <fbd><scaling x="1" y="1"/></fbd>
      <ld><scaling x="1" y="1"/></ld>
      <sfc><scaling x="1" y="1"/></sfc>
    </coordinateInfo>
  </contentHeader>
  <types>
    <dataTypes/>
    <pous>
      <pou name={quoteattr(pou_name)} pouType="program">
        <interface>
          <documentation>
            <xhtml xmlns="http://www.w3.org/1999/xhtml">{escape(decl)}</xhtml>
          </documentation>
        </interface>
        <body>
          <ST>
            <xhtml xmlns="http://www.w3.org/1999/xhtml">{escape(st_code)}</xhtml>
          </ST>
        </body>
      </pou>
    </pous>
  </types>
  <instances><configurations/></instances>
</project>
"""


def emit_scl(st_code: str, fb_name: str = "FB_Converted") -> str:
    """Siemens SCL (TIA Portal external source) from the generated ST.

    SCL and IEC ST are near-identical for the constructs we emit; the real
    differences are declaration syntax and timer FBs (TON -> IEC_TIMER /
    TON_TIME instance DBs). We emit an .scl external-source skeleton and
    flag the timer instances for TIA-side instantiation.
    """
    validate_iec_identifier(fb_name, "fb_name")
    reject_safety_text(st_code, fb_name)
    body = st_code
    # crude but honest transformations, each one documented in output
    body = re.sub(r"(?im)^(\s*)PROGRAM\s+[A-Za-z_][A-Za-z0-9_]*\s*$",
                  lambda match: f"{match.group(1)}FUNCTION_BLOCK {fb_name}",
                  body)
    body = re.sub(r"(?im)^(\s*)END_PROGRAM\s*$",
                  r"\1END_FUNCTION_BLOCK", body)
    header = (
        "// Siemens SCL external source — generated by dummvinci-rosetta-plc\n"
        "// IMPORT: TIA Portal -> External source files -> Add, then\n"
        "// 'Generate blocks from source'.\n"
        "// NOTE: TON instances declared as TON must be changed to\n"
        "//   {InstructionName := 'TON'; LibVersion := '1.0'} IEC_TIMER\n"
        "//   or multi-instance TON_TIME. Review every TODO marker —\n"
        "//   semantic hazards are identical to the ST output.\n\n")
    return header + body


