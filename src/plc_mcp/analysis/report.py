"""Migration report generator — one markdown document combining parse
summary, semantic hazard register, I/O mapping, and xref anomalies.

This is the artifact the presales/engineering team hands to the review
meeting: it makes the [VERIFY] set a formal checklist instead of tribal
knowledge, per PTTS verify-before-assume discipline.
"""
from __future__ import annotations

from datetime import date

from .. import __version__
from ..ir import Program
from .xref import build_xref
from .semantics import flag_semantics
from .iomap import map_io


def generate_report(prog: Program, project: str = "",
                    prepared_by: str = "dummvinci-rosetta-plc",
                    target: str | None = None,
                    io_profile: dict | None = None,
                    report_date: str | None = None) -> str:
    xref = build_xref(prog)
    flags = flag_semantics(prog)
    io = map_io(prog, io_profile)
    f_sum, x_sum, i_sum = flags["summary"], xref["summary"], io["summary"]

    lines = [
        f"# PLC Migration Analysis Report{' — ' + project if project else ''}",
        "",
        f"| | |",
        f"|---|---|",
        f"| Source dialect | {prog.source_dialect} |",
        f"| Program | {prog.name} |",
        f"| Date | {report_date or date.today().isoformat()} |",
        f"| Generated by | {prepared_by} (v{__version__}) |",
        *([f"| Target profile | {target} |"] if target else []),
        f"| I/O profile | {io['summary']['profile']} |",
        "",
        "> Machine-generated first pass. Every finding below requires "
        "engineering sign-off; nothing here is a commissioning decision.",
        "",
        "## 1. Parse summary",
        "",
        f"- Instructions: **{prog.meta.get('instruction_count', '?')}** in "
        f"**{prog.meta.get('rung_count', '?')}** networks",
        f"- Symbols loaded: {len(prog.symbols)}",
        f"- Unknown mnemonics: {prog.meta.get('unknown_mnemonics', 0)}"
        + (" ⚠️ extend parser before trusting coverage"
           if prog.meta.get('unknown_mnemonics') else ""),
        f"- Unparsed lines: {len(prog.meta.get('unparsed_lines', []))}",
        f"- Symbol conflicts (inline vs external comments): "
        f"{len(prog.meta.get('symbol_conflicts', []))}",
        "",
        "## 2. Semantic hazard register (assumption register)",
        "",
        f"**Verdict: {f_sum['verdict']}**",
        "",
    ]
    if f_sum.get("safety_boundary"):
        lines += [
            "> 🛑 **SAFETY BOUNDARY HIT.** Safety-instrumented function(s) "
            f"detected: {', '.join(f_sum.get('safety_categories', []))}. These "
            "are **out of scope** for this tool and must be engineered in a "
            "certified functional-safety toolchain (e.g. ABB AC500-S + "
            "SM560-S / PROFIsafe) under the IEC 61508/61511 lifecycle. A SIL "
            "rating is a property of the whole safety loop, not of generated "
            "code. See `SAFETY.md`.",
            "",
        ]
    lines += [
        f"| Severity | Count |",
        f"|---|---|",
        f"| BLOCKER | {f_sum.get('BLOCKER', 0)} |",
        f"| MAJOR | {f_sum.get('MAJOR', 0)} |",
        f"| MINOR | {f_sum.get('MINOR', 0)} |",
        "",
        "| Step | Code | Sev | Detail | Required action |",
        "|---|---|---|---|---|",
    ]
    for f in flags["flags"]:
        det = f["detail"].replace("|", "\\|")
        act = f["required_action"].replace("|", "\\|")
        lines.append(f"| {f['step']} | {f['code']} | {f['severity']} | "
                     f"{det} | {act} |")

    lines += [
        "",
        "## 3. I/O mapping proposal",
        "",
        f"- DI used/capacity: {i_sum['di_used']}/{i_sum['di_capacity']}",
        f"- DO relay used/capacity: {i_sum['do_relay_used']}/"
        f"{i_sum['do_relay_capacity']}",
        f"- DO DC used/capacity: {i_sum['do_dc_used']}/"
        f"{i_sum['do_dc_capacity']}",
        "",
    ]
    for w in io["warnings"]:
        lines.append(f"- ⚠️ {w}")
    lines += [
        "",
        "| Legacy | Symbol | Dir | Module | Ch | Note |",
        "|---|---|---|---|---|---|",
    ]
    for m in io["mapping"]:
        lines.append(f"| {m['legacy']} | {m['symbol']} | {m['direction']} | "
                     f"{m['module']} | {m['channel']} | {m['note']} |")

    lines += [
        "",
        "## 4. Cross-reference anomalies",
        "",
        f"- Devices total: {x_sum['device_count']}",
        f"- Double-coil (scan-order risk): "
        f"{', '.join(x_sum['multi_coil_devices']) or 'none'}",
        f"- Written but never read: "
        f"{', '.join(x_sum['written_never_read']) or 'none'}",
        f"- Read but never written (external/HMI-driven or missing scope): "
        f"{', '.join(x_sum['read_never_written']) or 'none'}",
        "",
    ]
    conflicts = prog.meta.get("symbol_conflicts", [])
    if conflicts:
        lines += ["Device-comment conflicts (kept value shown first — "
                  "confirm which is current):", ""]
        lines += [f"- {c['device']}: \"{c['kept']}\" vs \"{c['external']}\" "
                  f"({c['source']})" for c in conflicts]
        lines.append("")
    lines += [
        "## 5. Sign-off",
        "",
        "| Item | Decision | Engineer | Date |",
        "|---|---|---|---|",
    ]
    for f in [x for x in flags["flags"] if x["severity"] == "BLOCKER"]:
        lines.append(f"| Step {f['step']} {f['code']} |  |  |  |")
    lines.append("")
    return "\n".join(lines)
